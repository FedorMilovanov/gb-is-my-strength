import { chromium } from 'playwright';
const browser=await chromium.connectOverCDP('http://127.0.0.1:9222');
const ctx=browser.contexts()[0];
const p=await ctx.newPage();
const cdp=await p.context().newCDPSession(p);await cdp.send('Network.setCacheDisabled',{cacheDisabled:true});
const reqs=[];
p.on('response',async r=>{const u=r.url();if(u.startsWith('http://127.0.0.1:8080')){let b=0;try{const buf=await r.body();b=buf.length;}catch(e){}reqs.push({u:u.replace('http://127.0.0.1:8080',''),b,ct:(r.headers()['content-type']||'').slice(0,22)});}});
await p.setViewportSize({width:1280,height:900});
await p.goto('http://127.0.0.1:8080/articles/dzhon-gill-chast-1-chelovek/',{waitUntil:'load'});
await p.waitForTimeout(3500);
const dup={};reqs.forEach(r=>{dup[r.u]=(dup[r.u]||0)+1;});
const dups=Object.entries(dup).filter(([,c])=>c>1);
const js=reqs.filter(r=>r.u.endsWith('.js')||r.u.includes('_astro'));
const total=reqs.reduce((s,r)=>s+r.b,0);
console.log('requests:',reqs.length,'total transfer KB:',Math.round(total/1024));
console.log('duplicate URLs:',dups.length?dups:'none');
console.log('non-asset oddities:',reqs.filter(r=>/\.(br|bin|model|wasm|worker)/.test(r.u)).map(r=>r.u+' '+Math.round(r.b/1024)+'KB'));
console.log('js/astro KB:',Math.round(js.reduce((s,r)=>s+r.b,0)/1024));
const big=reqs.sort((a,b)=>b.b-a.b).slice(0,8).map(r=>Math.round(r.b/1024)+'KB '+r.u);
console.log('top8:',big);
await p.close();await browser.close();
