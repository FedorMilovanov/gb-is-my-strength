function renderPhotos(pl){
  if(!pl||!pl.photos||!pl.photos.length) return '';
  const items=pl.photos.map(p=>{
    const safeP=JSON.stringify({src:p.src,alt:p.alt||'',label:p.label||'',credit:p.credit||'',type:p.type||'ctx'}).replace(/"/g,'&quot;');
    return `<div class="tn-item" onclick="openPhotoModal(this)" data-photo="${safeP}" role="button" tabindex="0" aria-label="${p.alt||p.label||'Фото'}">
      <span class="tn-label ${p.type||'ctx'}">${p.label||''}</span>
      <img src="${p.thumb||p.src}" alt="${p.alt||''}" loading="lazy" width="320" height="180" onload="this.classList.add('loaded')" onerror="this.parentElement.style.display='none'">
      <div class="tn-cap">${(p.alt||'').substring(0,80)+(p.alt&&p.alt.length>80?'…':'')}</div>
    </div>`;
  }).join('');
  const credits=[...new Set(pl.photos.map(p=>p.credit).filter(Boolean))].map(c=>`<span>${c}</span>`).join(' · ');
  return `<div class="tn-gallery"><div class="tn-title">📷 ФОТО И РЕКОНСТРУКЦИИ</div><div class="tn-row">${items}</div>${credits?'<div class="tn-credit">'+credits+'</div>':''}</div>`;
}
