function clampView(v){
  v.w=Math.min(Math.max(v.w,240),2600);
  v.h=v.w*H0/W0;
  v.x=Math.min(Math.max(v.x,-450),W0+450-v.w);
  v.y=Math.min(Math.max(v.y,-380),H0+380-v.h);
  return v;
}
function flyTo(cx,cy,w,dur=900){
  const from={...view};const to=clampView({x:cx-w/2,y:cy-(w*H0/W0)/2,w:w,h:w*H0/W0});
  const t0=performance.now();
  cancelAnimationFrame(animId);
  function step(t){
    let p=Math.min((t-t0)/dur,1);p=1-Math.pow(1-p,3);
    view={x:from.x+(to.x-from.x)*p,y:from.y+(to.y-from.y)*p,w:from.w+(to.w-from.w)*p,h:from.h+(to.h-from.h)*p};
    applyView();
    if(p<1)animId=requestAnimationFrame(step);
  }
  animId=requestAnimationFrame(step);
}
function toSvg(cx,cy){
  const r=svg.getBoundingClientRect();
  const scale=Math.max(r.width/view.w,r.height/view.h);
  const vw=r.width/scale,vh=r.height/scale;
  const ox=view.x+(view.w-vw)/2, oy=view.y+(view.h-vh)/2;
  return{x:ox+(cx-r.left)/scale,y:oy+(cy-r.top)/scale,scale};
}

