/* ================= GSAP DRAWSVG on stage focus ================= */
function animateStageRoutes(stageIdx){
  if(typeof gsap==='undefined') return;
  if(window.matchMedia('(prefers-reduced-motion:reduce)').matches) return;
  const g=document.querySelectorAll('#routes g')[stageIdx];
  if(!g) return;
  const paths=[...g.querySelectorAll('.route')];
  paths.forEach((path,i)=>{
    const isDash=path.getAttribute('stroke-dasharray');
    const dur=isDash?1.2:1.8;
    gsap.fromTo(path,
      {drawSVG:'0%',filter:'url(#goldGlow)'},
      {drawSVG:'100%',duration:dur,ease:'power2.inOut',overwrite:true,
       onComplete:()=>{
         // убрать glow после прорисовки
         gsap.to(path,{filter:'',duration:.8,delay:.3});
       }
      }
    );
  });
}

