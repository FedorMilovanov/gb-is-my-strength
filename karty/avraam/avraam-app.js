function buildAmbient(){
  AC=AC||new (window.AudioContext||window.webkitAudioContext)();
  const master=AC.createGain();master.gain.value=0;master.connect(AC.destination);
  // desert wind: filtered noise
  const len=AC.sampleRate*4;
  const buf=AC.createBuffer(1,len,AC.sampleRate);
  const d=buf.getChannelData(0);let v=0;
  for(let i=0;i<len;i++){v=v*0.985+(Math.random()*2-1)*0.05;d[i]=v;}
  const noise=AC.createBufferSource();noise.buffer=buf;noise.loop=true;
  const nf=AC.createBiquadFilter();nf.type='bandpass';nf.frequency.value=320;nf.Q.value=.6;
  const ng=AC.createGain();ng.gain.value=.5;
  noise.connect(nf);nf.connect(ng);ng.connect(master);
  // slow LFO on wind
  const lfo=AC.createOscillator();lfo.frequency.value=.07;
  const lg=AC.createGain();lg.gain.value=120;
  lfo.connect(lg);lg.connect(nf.frequency);
  // drone: two detuned low oscillators (D2 + A2)
  const mk=(f,g)=>{const o=AC.createOscillator();o.type='sine';o.frequency.value=f;
    const og=AC.createGain();og.gain.value=g;o.connect(og);og.connect(master);o.start();return o;};
  const o1=mk(73.4,.05),o2=mk(110,.035),o3=mk(146.8,.02);
  noise.start();lfo.start();
  return{master,stop(){[noise,lfo,o1,o2,o3].forEach(n=>{try{n.stop()}catch(e){}});}};
}
