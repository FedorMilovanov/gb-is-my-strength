def update_file(path, new_body):
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    
    # Locate article body
    start_tag = '<article class="article-body">'
    end_tag = '</article>'
    
    start_idx = content.find(start_tag)
    end_idx = content.find(end_tag)
    
    if start_idx == -1 or end_idx == -1:
        print(f"Error: article tags not found in {path}")
        return False
        
    before_body = content[:start_idx + len(start_tag)]
    after_body = content[end_idx:]
    
    new_content = before_body + "\n" + new_body + "\n" + after_body
    
    # Also patch timeline-entry inline CSS inside head of biography pages
    new_content = new_content.replace(
        "background: var(--color-surface);",
        "background: var(--color-surface, #fdfcf9) !important; z-index: 2 !important;"
    )
    new_content = new_content.replace(
        "background: var(--color-surface, #fdfcf9);",
        "background: var(--color-surface, #fdfcf9) !important; z-index: 2 !important;"
    )
    
    # Remove biography-epigraph::before overlapping quote icon
    new_content = new_content.replace(
        ".biography-epigraph::before {",
        ".biography-epigraph::before { content: none !important; "
    )
    
    with open(path, "w", encoding="utf-8") as f:
        f.write(new_content)
    print(f"Successfully consolidated and deepened {path}")
    return True

