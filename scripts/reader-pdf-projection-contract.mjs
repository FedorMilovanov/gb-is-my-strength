import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { prepareReaderPdfProjection, injectReaderPdfMetadata } from './lib/reader-pdf-projection.mjs';

const hash = b => createHash('sha256').update(b).digest('hex');
const root = mkdtempSync(join(tmpdir(), 'gb-pdf-projection-test-'));
const route = '/articles/synthetic/';
const other = '/articles/other/';
const revision = 'a'.repeat(40);
const textHash = hash('synthetic reviewed text');
const html = '<!doctype html><html><head><title>Fixture</title></head><body><article>synthetic</article></body></html>';
const pdf = Buffer.from('%PDF-1.4 synthetic contract fixture only');
const sourceDist = join(root, 'dist');
const stage = join(root, 'stage');
const source = join(sourceDist, route, 'index.html');
const otherSource = join(sourceDist, other, 'index.html');
mkdirSync(join(sourceDist, route), { recursive: true });
mkdirSync(join(sourceDist, other), { recursive: true });
mkdirSync(stage);
writeFileSync(source, html);
writeFileSync(otherSource, html);
for (const w of [390,1440]) writeFileSync(join(stage,w+'.pdf'),pdf);
const receipt = { scope:'private-qa-only', revision, route, rendererProfile:'reader-native-a4-v1', sourceHash:hash(html), results:[390,1440].map(width=>({width,pages:2,bytes:pdf.length,sha256:hash(pdf),textHash})) };
const writeReceipt = r => writeFileSync(join(stage,'receipt.json'),JSON.stringify(r));
writeReceipt(receipt);
const args = { stages:[stage], revision, sourceDist, registry:{errors:[],entries:[route,other].map(route=>({route,routeRole:'reading',owner:'astro',status:'production-dist'}))}, approvals:[{route,scope:'standalone-pdf-distribution',status:'approved',evidence:'synthetic only'}], reviews:[{route,textHash,evidence:'synthetic only'}] };
let passed=0;
const check = fn => {fn();passed++;};
const fail = (fn,pattern) => check(()=>assert.throws(fn,pattern));
const entry = {route,filename:'synthetic.pdf',sha256:hash(pdf),url:'/reader-pdf/'+hash(pdf)+'/synthetic.pdf',bytes:pdf.length};
try {
 check(()=>{const result=prepareReaderPdfProjection(args);try{
 const e=result.manifest.entries[0];const projected=readFileSync(join(result.dir,route,'index.html'),'utf8');
 assert(projected.includes('name="gb-reader-pdf" content="'+e.url+'"'));
 assert(projected.includes('data-route="'+route+'"'));
 assert(projected.includes('data-revision="'+revision+'"'));
 assert.equal(projected.replace(/<meta name="gb-reader-pdf"[^>]*>\n/,''),html);
 assert.deepEqual(readFileSync(join(result.dir,e.url)),pdf);
 assert.equal(result.receipt.routes[0].sourceHash,hash(html));
 assert.equal(result.receipt.routes[0].projectedHash,hash(projected));
 assert(!existsSync(join(result.dir,other,'index.html')));
 assert.equal(readFileSync(source,'utf8'),html);
 assert.equal(readFileSync(otherSource,'utf8'),html);
 assert(!existsSync(join(sourceDist,'reader-pdf')));
 }finally{rmSync(result.dir,{recursive:true,force:true});}});
 check(()=>{const r=prepareReaderPdfProjection({...args,stages:[],approvals:[],reviews:[]});try{assert.equal(r.receipt.routes.length,0);assert.equal(r.receipt.artifacts,0);assert(!existsSync(join(r.dir,route,'index.html')));}finally{rmSync(r.dir,{recursive:true,force:true});}});
 fail(()=>prepareReaderPdfProjection({...args,approvals:[]}),/no explicit PDF approval/);
 fail(()=>prepareReaderPdfProjection({...args,reviews:[]}),/independent text review/);
 fail(()=>prepareReaderPdfProjection({...args,revision:'b'.repeat(40)}),/stale staged revision/);
 check(()=>{writeFileSync(source,html+'changed');try{assert.throws(()=>prepareReaderPdfProjection(args),/stale staged HTML/);}finally{writeFileSync(source,html);}});
 fail(()=>injectReaderPdfMetadata(html, {...entry,url:'https://bad.test/a.pdf'},revision),/invalid PDF URL/);
 fail(()=>injectReaderPdfMetadata(html, {...entry,url:'/reader-pdf/'+hash(pdf)+'/other.pdf'},revision),/Expected values/);
 fail(()=>injectReaderPdfMetadata(html, {...entry,route:'/../'},revision),/invalid projection route/);
 fail(()=>injectReaderPdfMetadata(html,entry,'bad'),/invalid source revision/);
 fail(()=>injectReaderPdfMetadata(html, {...entry,bytes:0},revision),/invalid PDF bytes/);
 fail(()=>injectReaderPdfMetadata(html.replace('</head>',''),entry,revision),/closing head/);
 fail(()=>injectReaderPdfMetadata(html.replace('</head>','</head></head>'),entry,revision),/closing head/);
 fail(()=>injectReaderPdfMetadata(html.replace('</head>','<meta name="gb-reader-pdf"></head>'),entry,revision),/duplicate PDF metadata/);
 console.log('Reader PDF projection contract: '+passed+'/14 PASS (synthetic only)');
} finally {rmSync(root,{recursive:true,force:true});}
